// Runs after `vite build --config vite.static.config.ts` (see `build:static` in package.json).
// Checks dist/client is safe to publish, then writes the Apache files for the SFTP host (IONOS):
//   .htaccess          clean URLs (/services -> services.html), 404 page, HTML not cached
//   assets/.htaccess   content-hashed files cached for a year
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const OUT = join(import.meta.dirname, "../../dist/client");
// Same default as vite.static.config.ts: the published Lovable app that runs the form backend.
const LOVABLE_APP_URL = (
  process.env.VITE_ENQUIRY_API_URL || "https://wmlegalservices.lovable.app"
).replace(/\/$/, "");
const fail = (message) => {
  console.error(`postbuild: ${message}`);
  process.exit(1);
};

for (const file of ["index.html", "404.html", "sitemap.xml", "robots.txt"]) {
  if (!existsSync(join(OUT, file))) fail(`dist/client/${file} is missing`);
}

// Every page in the sitemap must have been prerendered.
const sitemap = readFileSync(join(OUT, "sitemap.xml"), "utf8");
const pages = [...sitemap.matchAll(/<loc>https?:\/\/[^/<]+(\/[^<]*)<\/loc>/g)].map((m) => m[1]);
if (pages.length === 0) fail("sitemap.xml lists no pages");
for (const page of pages) {
  const file = page === "/" ? "index.html" : `${page.replace(/^\/|\/$/g, "")}.html`;
  if (!existsSync(join(OUT, file))) fail(`${page} is in sitemap.xml but ${file} was not prerendered`);
}

const walk = (dir, pattern, found = []) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, pattern, found);
    else if (pattern.test(name)) found.push(path);
  }
  return found;
};

// The host has no server runtime, so a server function would fail in the browser.
// Server code must live in a /api/public/* route, which runs on the Lovable app.
const SRC = join(import.meta.dirname, "../../src");
const serverFns = walk(SRC, /\.tsx?$/).filter((path) =>
  /\bcreateServerFn\s*\(/.test(readFileSync(path, "utf8")),
);
if (serverFns.length) {
  fail(`createServerFn can't run on the static host: ${serverFns.map((p) => relative(SRC, p)).join(", ")}`);
}

// Lovable-hosted media must use absolute URLs; "/__l5e/..." would 404 on the SFTP host.
let formPostsToLovable = false;
for (const path of walk(OUT, /\.(html|js|css)$/)) {
  const code = readFileSync(path, "utf8");
  const name = relative(OUT, path);
  if (/["'`(]\/__l5e\//.test(code)) fail(`${name} links to /__l5e/ on the static host`);
  if (code.includes("/api/public/enquiry") && code.includes(LOVABLE_APP_URL)) {
    formPostsToLovable = true;
  }
}
if (!formPostsToLovable) fail(`the enquiry form does not post to ${LOVABLE_APP_URL}`);

writeFileSync(
  join(OUT, ".htaccess"),
  `# Generated by scripts/static/postbuild.mjs; edit the generator, not this file.
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset UTF-8

<IfModule mod_rewrite.c>
RewriteEngine On
RewriteBase /

# One URL per page, as in the app's links and sitemap: /services/ -> /services
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^(.+)/$ /$1 [R=301,L]

# Prerendered pages: /services -> services.html (no "." in the pattern, so it can't loop)
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME}.html -f
RewriteRule ^([^.]+)$ $1.html [L]
</IfModule>

<IfModule mod_headers.c>
<FilesMatch "\\.(html|xml|txt)$">
Header set Cache-Control "no-cache"
</FilesMatch>
</IfModule>
`,
);

writeFileSync(
  join(OUT, "assets/.htaccess"),
  `<IfModule mod_headers.c>\nHeader set Cache-Control "public, max-age=31536000, immutable"\n</IfModule>\n`,
);

console.log(`postbuild: ${pages.length} pages verified (${pages.join(", ")}), .htaccess written`);
